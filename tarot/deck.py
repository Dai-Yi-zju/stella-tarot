def build_deck() -> list[Card]:
    """构建完整的 78 张牌。"""
    deck: list[Card] = []
    for i, (name, en, up, rev) in enumerate(_MAJOR):
        deck.append(Card(i, name, en, "大阿尔卡那", "大牌", up, rev))

    idx = len(deck)
    for (suit_cn, suit_en, element), meanings in _MINOR.items():
        for (rank_cn, rank_en), (up, rev) in zip(_RANKS, meanings):
            deck.append(Card(
                idx,
                f"{suit_cn}{rank_cn}",
                f"{rank_en} of {suit_en}",
                "小阿尔卡那",
                f"{suit_cn}（{element}）",
                up,
                rev,
            ))
            idx += 1

    assert len(deck) == 78, f"牌数应为 78，实际为 {len(deck)}"
    return deck
